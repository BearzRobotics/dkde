test "library functions agree with Qalculate" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var session: eval.Session = .{ .gpa = std.testing.allocator };
    defer session.deinit();
    var failures: usize = 0;
    for (cases) |c| {
        var p: eval.Problem = .{};
        const o = eval.run(a, &session, c[0], .{ .angle = .radians }, &p) catch |e| {
            std.debug.print("{s}: error {s}\n", .{ c[0], @errorName(e) });
            failures += 1;
            continue;
        };
        const got = switch (o) {
            .value => |v| v.toFloat(),
            else => {
                failures += 1;
                continue;
            },
        };
        const want = try std.fmt.parseFloat(f64, c[1]);
        const tol: f64 = 1e-11 * @abs(want) + (if (want == 0) @as(f64, 1e-14) else @as(f64, 1e-300));
        if (@abs(got - want) > tol) {
            std.debug.print("{s}: got {d:.15}, Qalculate {s}\n", .{ c[0], got, c[1] });
            failures += 1;
        }
    }
    try std.testing.expectEqual(@as(usize, 0), failures);
}
